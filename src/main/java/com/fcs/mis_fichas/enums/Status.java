package com.fcs.mis_fichas.enums;

/**
 * Enum que representa los estados posibles de una cuenta de usuario.
 */
public enum Status {
    /**
     * Cuenta activa y habilitada para iniciar sesión.
     */
    ACTIVE,
    /**
     * Cuenta bloqueada y deshabilitada para iniciar sesión.
     */
    BLOCKED
}
